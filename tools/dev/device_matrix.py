"""Builds the table of tablets and features from knowledge/devices.json, into DEVICES.md and the site.

Run: python tools/dev/device_matrix.py           (rewrites the generated part of both files)
     python tools/dev/device_matrix.py --check   (prints what is out of date and exits 1 if anything is)
The unit test test_device_matrix.py runs the check over the repository on every push.

Each file keeps its own words around the table: only the lines between the two markers below are generated.
"""
import html
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DATA = os.path.join(ROOT, 'knowledge', 'devices.json')
MARKDOWN = os.path.join(ROOT, 'DEVICES.md')
SITE = os.path.join(ROOT, 'site', 'index.html')
START = '<!-- device-matrix:start: generated by tools/dev/device_matrix.py from knowledge/devices.json, edit those -->'
END = '<!-- device-matrix:end -->'

# status -> (label, Markdown symbol, what it means). Order is the legend's.
STATUSES = {
    'v': ('Checked', '●', 'by the maintainer, on that tablet, or on the emulator for the last column.'),
    'r': ('Reported working', '◐', "by the tablet's owner, and not yet checked by the maintainer."),
    'p': ('Partly checked', '◔', "the note says which part isn't checked yet."),
    'b': ('Not yet seen working', '○', 'built for that tablet, and nobody has seen it work there yet.'),
    'x': ("Doesn't work", '✕', 'reported or found not to work there.'),
    'n': ('Not offered', '–', 'BooxUltimatum hides it on that tablet.'),
    '': ('No report yet', '', 'nobody has reported on it, which says nothing about whether it works.'),
}
WORKING = ('v', 'r', 'p')


def load(path=DATA):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def cell(feature, device_id):
    """(status, note or None) for one feature on one tablet."""
    value = feature['cells'].get(device_id, '')
    status, note = (value[0], value[1]) if isinstance(value, list) else (value, None)
    if status not in STATUSES:
        raise ValueError(f'{feature["name"]}: unknown status {status!r} for {device_id}')
    return status, note


def validate(data):
    ids = [d['id'] for d in data['devices']]
    for group in data['groups']:
        for feature in group['features']:
            for device_id in feature['cells']:
                if device_id not in ids:
                    raise ValueError(f'{feature["name"]}: no tablet called {device_id!r}')
                cell(feature, device_id)


def numbered_notes(data):
    """Each note's text -> its number, in reading order; a note used in several cells is numbered once."""
    numbers = {}
    for group in data['groups']:
        for feature in group['features']:
            for device in data['devices']:
                _, note = cell(feature, device['id'])
                if note and note not in numbers:
                    numbers[note] = len(numbers) + 1
    return numbers


def tallies(data):
    """Per tablet: how many features were seen working (checked, reported or partly checked), and of how many."""
    features = [f for g in data['groups'] for f in g['features']]
    return {d['id']: sum(cell(f, d['id'])[0] in WORKING for f in features) for d in data['devices']}, len(features)


# Markdown ---------------------------------------------------------------------------------------------------------

def markdown(data):
    validate(data)
    notes = numbered_notes(data)
    seen, total = tallies(data)
    devices = data['devices']
    out = [START, '']
    for key, (label, symbol, meaning) in STATUSES.items():
        out.append(f'- {symbol or "(blank)"} **{label}:** {meaning}')
    out.append('')
    out.append('| Feature | Access | ' + ' | '.join(f'{d["name"]}<br><sub>{d["detail"]}</sub>' for d in devices) + ' |')
    out.append('| :-- | :-: | ' + ' | '.join(':-:' for _ in devices) + ' |')
    for group in data['groups']:
        title = f'**{group["name"]}**' + (f' · needs {group["needs"]}' if group.get('needs') else '')
        out.append(f'| {title} |  | ' + ' | '.join('' for _ in devices) + ' |')
        for feature in group['features']:
            cells = []
            for d in devices:
                status, note = cell(feature, d['id'])
                text = STATUSES[status][1]
                if note:
                    text = (text + ' ' if text else '') + f'<sup>{notes[note]}</sup>'
                cells.append(text)
            out.append(f'| {feature["name"]} | {feature["tier"]} | ' + ' | '.join(cells) + ' |')
    out.append('| *Seen working* |  | ' + ' | '.join(f'{seen[d["id"]]} of {total}' for d in devices) + ' |')
    out += ['', '### Notes', '']
    out += [f'{n}. {text}' for text, n in notes.items()]
    out += ['', '### Where each column comes from', '']
    out += [f'- **{d["name"]}:** {d["about"]}' for d in devices]
    out += ['', END]
    return '\n'.join(out)


# The site ---------------------------------------------------------------------------------------------------------

def esc(text):
    return html.escape(text, quote=True)


def site(data, indent='    '):
    validate(data)
    notes = numbered_notes(data)
    seen, total = tallies(data)
    devices = data['devices']
    out = [START, '<ul class="legend" aria-label="What a cell means">']
    for key, (label, _, meaning) in STATUSES.items():
        out.append(f'  <li><span class="ev ev-{key or "0"}" aria-hidden="true"></span><span><b>{esc(label)}</b>{esc(meaning[0].upper() + meaning[1:])}</span></li>')
    out.append('</ul>')
    out.append('<div class="matrix-wrap" role="region" aria-labelledby="tablets-title" tabindex="0">')
    out.append('<table class="matrix">')
    out.append('  <caption class="vh">Features by tablet. Each row is a feature with the access it needs; each column is a tablet, and its cell says what is known there.</caption>')
    out.append('  <thead>')
    out.append('    <tr>')
    out.append('      <th scope="col" class="feat">Feature</th>')
    out.append('      <th scope="col" class="acc">Access</th>')
    for d in devices:
        if d.get('reference'):
            source = f'<span class="lamp" aria-hidden="true"></span>{esc(d["source"])}'
        else:
            links = ' '.join(f'<a href="{esc(url)}">{esc(text)}</a>' for text, url in d['links'])
            source = esc(d['source']) + (f' {links}' if links else '')
        ref = ' class="ref"' if d.get('reference') else ''
        out.append(f'      <th scope="col"{ref}><span class="dev">{esc(d["name"])}</span><span class="fw">{esc(d["detail"])}</span><span class="src">{source}</span></th>')
    out.append('    </tr>')
    out.append('  </thead>')
    for group in data['groups']:
        out.append('  <tbody>')
        needs = f'<span>Needs {esc(group["needs"])}</span>' if group.get('needs') else ''
        # The heading spans the two label columns only, so the reference column's frame runs on through it.
        empty = ''.join('<td class="ref"></td>' if d.get('reference') else '<td></td>' for d in devices)
        out.append(f'    <tr class="group"><th scope="rowgroup" colspan="2"><span class="g">{esc(group["name"])}{needs}</span></th>{empty}</tr>')
        for feature in group['features']:
            out.append('    <tr>')
            out.append(f'      <th scope="row">{esc(feature["name"])}</th>')
            out.append(f'      <td class="acc">{esc(feature["tier"])}</td>')
            for d in devices:
                status, note = cell(feature, d['id'])
                label = STATUSES[status][0]
                title = f'{d["name"]} · {feature["name"]}: {label}.' + (f' {note}' if note else '')
                mark = f'<sup class="fn"><a href="#dn-{notes[note]}" aria-label="Note {notes[note]}">{notes[note]}</a></sup>' if note else ''
                ref = ' class="ref"' if d.get('reference') else ''
                out.append(f'      <td{ref} title="{esc(title)}"><span class="ev ev-{status or "0"}" aria-hidden="true"></span><span class="vh">{esc(label)}</span>{mark}</td>')
            out.append('    </tr>')
        out.append('  </tbody>')
    out.append('  <tfoot>')
    out.append('    <tr>')
    out.append('      <th scope="row">Seen working</th>')
    out.append('      <td class="acc"></td>')
    for d in devices:
        share = round(100 * seen[d['id']] / total)
        ref = ' class="ref"' if d.get('reference') else ''
        out.append(f'      <td{ref}><span class="tally" aria-hidden="true"><span style="width:{share}%"></span></span>{seen[d["id"]]} of {total}</td>')
    out.append('    </tr>')
    out.append('  </tfoot>')
    out.append('</table>')
    out.append('</div>')
    out.append('<ol class="matrix-notes">')
    out += [f'  <li id="dn-{n}">{esc(text)}</li>' for text, n in notes.items()]
    out.append('</ol>')
    out.append(END)
    return '\n'.join(indent + line if line else line for line in out)


# Files ------------------------------------------------------------------------------------------------------------

def replaced(text, block, path):
    """The file's text with the generated block swapped in, keeping the indentation of the start marker."""
    start = text.find(START)
    end = text.find(END)
    if start < 0 or end < start:
        raise ValueError(f'{os.path.relpath(path, ROOT)}: the markers of the generated table are missing')
    line_start = text.rfind('\n', 0, start) + 1
    return text[:line_start] + block + text[end + len(END):]


def targets(data):
    return (MARKDOWN, markdown(data)), (SITE, site(data))


def problems(data=None):
    """The files whose generated table differs from the data."""
    data = data or load()
    stale = []
    for path, block in targets(data):
        with open(path, encoding='utf-8') as f:
            text = f.read()
        if replaced(text, block, path) != text:
            stale.append(os.path.relpath(path, ROOT))
    return stale


def write(data=None):
    data = data or load()
    for path, block in targets(data):
        with open(path, encoding='utf-8') as f:
            text = f.read()
        new = replaced(text, block, path)
        if new != text:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new)
            print(f'wrote {os.path.relpath(path, ROOT)}')


def main():
    if '--check' in sys.argv:
        stale = problems()
        for path in stale:
            print(f'{path}: out of date with knowledge/devices.json; run python tools/dev/device_matrix.py')
        return 1 if stale else 0
    write()
    return 0


if __name__ == '__main__':
    sys.exit(main())
